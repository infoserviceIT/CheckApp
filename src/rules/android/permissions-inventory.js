import {
  PERMISSION_CATALOG,
  DATA_SAFETY_PERMISSIONS,
  isAutoGeneratedPermission,
} from './permission-catalog.js';

// This rule does three things with the manifest's declared permissions —
// see permission-catalog.js for the data behind points 2 and 3:
//  1. Always emits a baseline 'info' finding listing everything declared
//     (this is the original, inventory-only version of this rule).
//  2. Emits one 'warn' finding *per* restricted permission found, each with
//     its own concrete remediation — these are the ones that can actually
//     get a submission rejected if mishandled.
//  3. Emits one consolidated 'warn' finding listing every declared
//     permission that maps to a Data Safety category, as a reminder to
//     double check the Data Safety form matches.
// None of this is scored as a hard pass/fail: whether a restricted
// permission is actually a problem depends on whether its Play Console
// declaration and in-app disclosure are done, which isn't visible from a
// manifest alone — hence 'warn', never 'fail'.
//
// Android's own auto-generated *.DYNAMIC_RECEIVER_NOT_EXPORTED_PERMISSION is
// filtered out everywhere below (including the baseline count) — it's not
// something the developer declared and flagging it would just be noise.

export const rule = {
  id: 'android.manifest.permissions-inventory',
  title: 'Declared permissions (inventory, not yet scored)',
  platform: 'android',
  severity: 'medium',
  guideline: 'Google Play Console Help — Data safety',

  /** @param {import('../../inspectors/android-bundletool.js').AndroidManifestData} data */
  evaluate(data) {
    const permissions = data.permissions.filter((p) => !isAutoGeneratedPermission(p));
    const results = [];

    if (permissions.length === 0) {
      results.push({ status: 'info', detail: 'No uses-permission entries found.' });
    } else {
      results.push({
        status: 'info',
        detail:
          `${permissions.length} permission(s) declared: ${permissions.join(', ')}. ` +
          `Check each against the app's Data Safety declaration in Play Console.`,
      });
    }

    for (const permission of permissions) {
      const entry = PERMISSION_CATALOG[permission];
      if (!entry) continue;
      const name = shortName(permission);
      results.push({
        id: `${rule.id}.restricted.${name}`,
        title: `Restricted permission: ${name}`,
        status: 'warn',
        severity: entry.severity,
        detail: entry.why,
        remediation: entry.remediation,
        guideline: entry.guideline,
      });
    }

    const dataSafetyPermissions = permissions.filter((p) => DATA_SAFETY_PERMISSIONS[p]);
    if (dataSafetyPermissions.length > 0) {
      const categories = [...new Set(dataSafetyPermissions.map((p) => DATA_SAFETY_PERMISSIONS[p]))];
      results.push({
        id: `${rule.id}.data-safety`,
        title: 'Data Safety form likely needs updating',
        status: 'warn',
        detail:
          `${dataSafetyPermissions.length} declared permission(s) map to Data Safety ` +
          `categories: ${categories.join(', ')} (from ${dataSafetyPermissions.map(shortName).join(', ')}).`,
        remediation:
          'Open Play Console → App content → Data safety, and make sure each of these categories ' +
          'is declared with the correct collection/sharing purpose — a mismatch between requested ' +
          'permissions and the Data Safety form is a common review flag.',
        guideline: 'Google Play Console Help — Data safety',
      });
    }

    return results;
  },
};

function shortName(permission) {
  return permission.replace(/^android\.permission\./, '');
}
